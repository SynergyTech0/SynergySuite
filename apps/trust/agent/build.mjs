// Bundles the agent for deployment to a host: the agent script plus the collector modules
// it imports. Copying the collectors rather than reimplementing them is deliberate — the
// same code means an observation has the same meaning wherever it was made.
import { mkdirSync, copyFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'dist');
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'collectors'), { recursive: true });

copyFileSync(join(here, 'strust-agent.mjs'), join(out, 'strust-agent.mjs'));

// Only the collectors that can run locally. Self-referential ones read the SERVER's
// database and make no sense on a customer host; shipping them would invite an agent to
// fail nightly at something it was never able to do.
const SKIP = new Set(['audit-integrity.mjs']);
const src = join(here, '..', 'src', 'lib', 'collectors');
const copied = [];
for (const f of readdirSync(src)) {
  if (!f.endsWith('.mjs') || SKIP.has(f)) continue;
  copyFileSync(join(src, f), join(out, 'collectors', f));
  copied.push(f);
}

// The registry imports every collector, including the ones not shipped. Rewrite it to the
// subset actually present, so the agent cannot fail at import time.
const kept = copied.filter((f) => f !== 'registry.mjs' && f !== 'ssh.mjs');
const names = kept.map((f) => f.replace('.mjs', '').replace(/-([a-z])/g, (_, c) => c.toUpperCase()));
writeFileSync(
  join(out, 'collectors', 'registry.mjs'),
  `// Generated by agent/build.mjs — the collectors that can run on a host.\n` +
    kept.map((f, i) => `import * as ${names[i]} from './${f}';`).join('\n') +
    `\n\nconst ALL = [${names.join(', ')}];\n\n` +
    `export const COLLECTORS = new Map(ALL.map((c) => [c.kind, c]));\n` +
    `export function collectorCatalogue() {\n` +
    `  return ALL.map((c) => ({ kind: c.kind, version: c.version, title: c.title }));\n}\n`,
);

writeFileSync(
  join(out, 'package.json'),
  JSON.stringify({ name: 'strust-agent', version: '0.1.0', type: 'module', private: true }, null, 2) + '\n',
);

writeFileSync(
  join(out, 'README.md'),
  `# Synergy Trust collector agent\n\n` +
    `Runs on a monitored host. Asks the server what to measure, measures it locally, posts\n` +
    `the results back. Nothing listens, nothing inbound is needed, and the server holds no\n` +
    `credentials into this machine.\n\n` +
    `    STRUST_SERVER=https://trust.example.com \\n` +
    `    STRUST_AGENT_TOKEN=<shown once at enrolment> \\n` +
    `    node strust-agent.mjs --once\n\n` +
    `Collectors shipped: ${kept.filter((f) => f !== 'registry.mjs').map((f) => f.replace('.mjs', '')).join(', ')}\n\n` +
    `Requires Node 18+. Nothing else — no dependencies to install.\n`,
);

console.log(`agent bundle built in ${out}`);
console.log(`  collectors: ${kept.filter((f) => f !== 'registry.mjs').join(', ')}`);
